    function gs1Lookup(list) {
        const pad = (n) => String(n).padStart(3, '0');
        return {
            q: '',
            range(r) { return r[0] === r[1] ? pad(r[0]) : pad(r[0]) + '–' + pad(r[1]); },
            find(p) { return list.find((r) => p >= r[0] && p <= r[1]); },
            get res() {
                let d = (this.q || '').replace(/\D/g, '');
                if (!d) return { kind: 'none', note: 'Tapez par exemple 3, 611 ou un code complet de 13 chiffres.' };
                let note = '';
                if (d.length === 12) { d = '0' + d; note = 'Code à 12 chiffres : UPC-A américain. '; }
                else if (d.length === 14) { d = d.slice(1); note = 'Code à 14 chiffres (GTIN-14, carton) : le premier chiffre est ignoré. '; }
                if (d.length < 3) {
                    const from = parseInt(d.padEnd(3, '0'), 10), to = parseInt(d.padEnd(3, '9'), 10);
                    const l = list.filter((r) => r[1] >= from && r[0] <= to);
                    return l.length ? { kind: 'many', prefix: d, list: l } : { kind: 'none', note: 'Aucun préfixe ne commence par ' + d + '.' };
                }
                const p = parseInt(d.slice(0, 3), 10), r = this.find(p);
                if (!r) return { kind: 'one', prefix: d.slice(0, 3), name: 'Préfixe non attribué', note: note + 'GS1 garde ce préfixe en réserve : aucun pays ne l’utilise pour le moment.' };
                if (d.length === 13 || d.length === 8) {
                    const digits = d.split('').map(Number), last = digits.pop();
                    const sum = digits.reverse().reduce((s, x, i) => s + x * (i % 2 === 0 ? 3 : 1), 0);
                    note += (10 - sum % 10) % 10 === last ? 'La clé de contrôle est juste. ' : 'Attention : la clé de contrôle ne correspond pas, le code est peut-être mal tapé. ';
                }
                if (r[3] === 'pays') note += 'Le préfixe indique où la marque a obtenu ses codes, pas forcément où le produit est fabriqué.';
                return { kind: 'one', prefix: d.slice(0, 3), name: r[2], note: note.trim() };
            },
        };
    }
